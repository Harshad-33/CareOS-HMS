    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,
    CONSTRAINT pk_leave_applications PRIMARY KEY (id),
    CONSTRAINT uk_leave_app_pub UNIQUE (public_id),
    CONSTRAINT fk_leave_app_hosp FOREIGN KEY (hospital_id) REFERENCES hospitals(id),
    CONSTRAINT fk_leave_app_emp FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
    CONSTRAINT fk_leave_app_type FOREIGN KEY (leave_type_id) REFERENCES leave_types(id),
    INDEX idx_leave_app_emp_status (hospital_id, employee_id, status),
    INDEX idx_leave_app_hosp_status (hospital_id, status, current_step_number),
    INDEX idx_leave_app_dates (hospital_id, start_date, end_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

