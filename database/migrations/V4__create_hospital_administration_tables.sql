-- CareOS-HMS Phase 3 Hospital Administration Schema
-- Extends hospitals table and adds hospital settings, documents, contacts, departments, branches, and audit logs.

ALTER TABLE hospitals
    ADD COLUMN registration_number VARCHAR(64) NULL AFTER hospital_code,
    ADD COLUMN hospital_type VARCHAR(32) NOT NULL DEFAULT 'GENERAL' AFTER name,
    ADD COLUMN email VARCHAR(160) NULL AFTER hospital_type,
    ADD COLUMN primary_contact_number VARCHAR(32) NULL AFTER email,
    ADD COLUMN alternate_contact_number VARCHAR(32) NULL AFTER primary_contact_number,
    ADD COLUMN website VARCHAR(255) NULL AFTER alternate_contact_number,
    ADD COLUMN address_line_1 VARCHAR(255) NULL AFTER website,
    ADD COLUMN address_line_2 VARCHAR(255) NULL AFTER address_line_1,
    ADD COLUMN city VARCHAR(100) NULL AFTER address_line_2,
    ADD COLUMN district VARCHAR(100) NULL AFTER city,
    ADD COLUMN state VARCHAR(100) NULL AFTER district,
    ADD COLUMN country VARCHAR(100) NOT NULL DEFAULT 'India' AFTER state,
    ADD COLUMN pin_code VARCHAR(20) NULL AFTER country,
    ADD COLUMN established_date DATE NULL AFTER pin_code,
    ADD CONSTRAINT uk_hospitals_reg_number UNIQUE (registration_number),
    ADD INDEX idx_hospitals_city_state (city, state);

CREATE TABLE hospital_settings (
    id BIGINT NOT NULL AUTO_INCREMENT,
    hospital_id BIGINT NOT NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Kolkata',
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',
    date_format VARCHAR(32) NOT NULL DEFAULT 'YYYY-MM-DD',
    time_format VARCHAR(16) NOT NULL DEFAULT '24_HOUR',
    working_days VARCHAR(100) NOT NULL DEFAULT 'MONDAY,TUESDAY,WEDNESDAY,THURSDAY,FRIDAY,SATURDAY',
    working_hours_start TIME NOT NULL DEFAULT '09:00:00',
    working_hours_end TIME NOT NULL DEFAULT '18:00:00',
    appointment_slot_duration_minutes INT NOT NULL DEFAULT 15,
    max_advance_booking_days INT NOT NULL DEFAULT 30,
    emergency_contact_number VARCHAR(32) NULL,
    support_email VARCHAR(160) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    CONSTRAINT pk_hospital_settings PRIMARY KEY (id),
    CONSTRAINT uk_hospital_settings_hospital_id UNIQUE (hospital_id),
    CONSTRAINT fk_hospital_settings_hospitals FOREIGN KEY (hospital_id) REFERENCES hospitals (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE hospital_documents (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(36) NOT NULL,
    hospital_id BIGINT NOT NULL,
    document_type VARCHAR(64) NOT NULL,
    document_name VARCHAR(255) NOT NULL,
    file_key VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    upload_date DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    expiry_date DATE NULL,
    verification_status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    verified_at DATETIME(6) NULL,
    verified_by VARCHAR(100) NULL,
    rejection_reason VARCHAR(255) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,
    CONSTRAINT pk_hospital_documents PRIMARY KEY (id),
    CONSTRAINT uk_hospital_documents_public_id UNIQUE (public_id),
    CONSTRAINT uk_hospital_documents_file_key UNIQUE (file_key),
    CONSTRAINT fk_hospital_documents_hospitals FOREIGN KEY (hospital_id) REFERENCES hospitals (id),
    INDEX idx_hosp_docs_hosp_status (hospital_id, verification_status, is_deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE hospital_contacts (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(36) NOT NULL,
    hospital_id BIGINT NOT NULL,
    contact_type VARCHAR(32) NOT NULL DEFAULT 'GENERAL',
    name VARCHAR(100) NOT NULL,
    designation VARCHAR(100) NULL,
    phone_number VARCHAR(32) NOT NULL,
    email VARCHAR(160) NULL,
    is_primary TINYINT(1) NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,
    CONSTRAINT pk_hospital_contacts PRIMARY KEY (id),
    CONSTRAINT uk_hospital_contacts_public_id UNIQUE (public_id),
    CONSTRAINT fk_hospital_contacts_hospitals FOREIGN KEY (hospital_id) REFERENCES hospitals (id),
    INDEX idx_hosp_contacts_hosp (hospital_id, is_deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE departments (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(36) NOT NULL,
    hospital_id BIGINT NOT NULL,
    department_code VARCHAR(32) NOT NULL,
    department_name VARCHAR(100) NOT NULL,
    description VARCHAR(255) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,
    CONSTRAINT pk_departments PRIMARY KEY (id),
    CONSTRAINT uk_departments_public_id UNIQUE (public_id),
    CONSTRAINT uk_dept_hospital_code UNIQUE (hospital_id, department_code),
    CONSTRAINT fk_departments_hospitals FOREIGN KEY (hospital_id) REFERENCES hospitals (id),
    INDEX idx_departments_hospital_status (hospital_id, status, is_deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE hospital_branches (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(36) NOT NULL,
    hospital_id BIGINT NOT NULL,
    branch_code VARCHAR(32) NOT NULL,
    branch_name VARCHAR(100) NOT NULL,
    contact_number VARCHAR(32) NULL,
    email VARCHAR(160) NULL,
    address VARCHAR(255) NULL,
    city VARCHAR(100) NULL,
    district VARCHAR(100) NULL,
    state VARCHAR(100) NULL,
    country VARCHAR(100) NOT NULL DEFAULT 'India',
    pin_code VARCHAR(20) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,
    CONSTRAINT pk_hospital_branches PRIMARY KEY (id),
    CONSTRAINT uk_hospital_branches_public_id UNIQUE (public_id),
    CONSTRAINT uk_branch_hospital_code UNIQUE (hospital_id, branch_code),
    CONSTRAINT fk_hospital_branches_hospitals FOREIGN KEY (hospital_id) REFERENCES hospitals (id),
    INDEX idx_branches_hospital_status (hospital_id, status, is_deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE audit_logs (
    id BIGINT NOT NULL AUTO_INCREMENT,
    actor_user_id BIGINT NULL,
    actor_username VARCHAR(64) NOT NULL,
    hospital_id BIGINT NULL,
    action VARCHAR(64) NOT NULL,
    entity_name VARCHAR(64) NOT NULL,
    entity_id VARCHAR(64) NULL,
    description VARCHAR(255) NULL,
    metadata_json TEXT NULL,
    client_ip VARCHAR(64) NULL,
    timestamp DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_audit_logs PRIMARY KEY (id),
    CONSTRAINT fk_audit_logs_users FOREIGN KEY (actor_user_id) REFERENCES users (id),
    CONSTRAINT fk_audit_logs_hospitals FOREIGN KEY (hospital_id) REFERENCES hospitals (id),
    INDEX idx_audit_logs_hosp_timestamp (hospital_id, timestamp),
    INDEX idx_audit_logs_actor_timestamp (actor_username, timestamp),
    INDEX idx_audit_logs_entity (entity_name, entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
