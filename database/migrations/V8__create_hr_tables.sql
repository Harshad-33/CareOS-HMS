-- CareOS-HMS Phase 5 HR Management Schema
-- Implements Leave Policies, Double-Entry Leave Balances, Multi-Level Approvals,
-- Shifts, Clinical Duty Rosters, Daily Attendance, Biometric Ingest, Holidays, and HR Documents.

-- 1. Leave Types & Policy Configuration
CREATE TABLE leave_types (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(36) NOT NULL,
    hospital_id BIGINT NOT NULL,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255) NULL,
    annual_allowance INT NOT NULL DEFAULT 12,
    carry_forward_enabled TINYINT(1) NOT NULL DEFAULT 0,
    max_carry_forward_days INT NOT NULL DEFAULT 0,
    medical_cert_required TINYINT(1) NOT NULL DEFAULT 0,
    min_service_days_required INT NOT NULL DEFAULT 0,
    is_paid TINYINT(1) NOT NULL DEFAULT 1,
    approval_workflow_type VARCHAR(32) NOT NULL DEFAULT 'MANAGER_THEN_HR',
    approval_levels_count INT NOT NULL DEFAULT 2,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,
    CONSTRAINT pk_leave_types PRIMARY KEY (id),
    CONSTRAINT uk_leave_types_public_id UNIQUE (public_id),
    CONSTRAINT uk_leave_types_hosp_code UNIQUE (hospital_id, code),
    CONSTRAINT fk_leave_types_hospital FOREIGN KEY (hospital_id) REFERENCES hospitals(id),
    INDEX idx_leave_types_hosp_status (hospital_id, status, is_deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. Leave Balances with Optimistic Locking
CREATE TABLE leave_balances (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(36) NOT NULL,
    hospital_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    leave_type_id BIGINT NOT NULL,
    calendar_year INT NOT NULL,
    total_allocated DECIMAL(5,2) NOT NULL DEFAULT 0.00,
    used_days DECIMAL(5,2) NOT NULL DEFAULT 0.00,
    pending_approval_days DECIMAL(5,2) NOT NULL DEFAULT 0.00,
    available_balance DECIMAL(5,2) NOT NULL DEFAULT 0.00,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    CONSTRAINT pk_leave_balances PRIMARY KEY (id),
    CONSTRAINT uk_leave_balances_public_id UNIQUE (public_id),
    CONSTRAINT uk_leave_balances_emp_year UNIQUE (hospital_id, employee_id, leave_type_id, calendar_year),
    CONSTRAINT fk_leave_balances_hosp FOREIGN KEY (hospital_id) REFERENCES hospitals(id),
    CONSTRAINT fk_leave_balances_emp FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
    CONSTRAINT fk_leave_balances_type FOREIGN KEY (leave_type_id) REFERENCES leave_types(id),
    INDEX idx_leave_balances_emp (hospital_id, employee_id, calendar_year)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. Leave Balance Transactions (Double-Entry Ledger)
CREATE TABLE leave_balance_transactions (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(36) NOT NULL,
    hospital_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    leave_type_id BIGINT NOT NULL,
    transaction_type VARCHAR(32) NOT NULL,
