    balance_before DECIMAL(5,2) NOT NULL,
    balance_after DECIMAL(5,2) NOT NULL,
    reference_id VARCHAR(36) NULL,
    remarks VARCHAR(255) NULL,
    actor_username VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_leave_bal_tx PRIMARY KEY (id),
    CONSTRAINT uk_leave_bal_tx_pub UNIQUE (public_id),
    CONSTRAINT fk_leave_bal_tx_hosp FOREIGN KEY (hospital_id) REFERENCES hospitals(id),
    CONSTRAINT fk_leave_bal_tx_emp FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
    CONSTRAINT fk_leave_bal_tx_type FOREIGN KEY (leave_type_id) REFERENCES leave_types(id),
    INDEX idx_leave_tx_emp (hospital_id, employee_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. Leave Applications
