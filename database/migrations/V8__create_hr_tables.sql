    comments VARCHAR(255) NULL,
    rejection_reason VARCHAR(255) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    CONSTRAINT pk_leave_approvals PRIMARY KEY (id),
    CONSTRAINT uk_leave_approvals_pub UNIQUE (public_id),
    CONSTRAINT uk_leave_app_step UNIQUE (leave_application_id, step_number),
    CONSTRAINT fk_leave_approvals_hosp FOREIGN KEY (hospital_id) REFERENCES hospitals(id),
    CONSTRAINT fk_leave_approvals_app FOREIGN KEY (leave_application_id) REFERENCES leave_applications(id) ON DELETE CASCADE,
