-- CareOS-HMS Phase 4 Employee Management Schema
-- Implements hospital-scoped employee registry, professional assignments, and lifecycle tracking.

CREATE TABLE employees (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(36) NOT NULL,
    hospital_id BIGINT NOT NULL,
    user_id BIGINT NULL,
    employee_number VARCHAR(32) NOT NULL,
    first_name VARCHAR(80) NOT NULL,
    middle_name VARCHAR(80) NULL,
    last_name VARCHAR(80) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(16) NOT NULL,
    blood_group VARCHAR(16) NULL,
    email VARCHAR(160) NOT NULL,
    phone_number VARCHAR(32) NOT NULL,
    alternate_phone_number VARCHAR(32) NULL,
    address_line_1 VARCHAR(255) NULL,
    address_line_2 VARCHAR(255) NULL,
    city VARCHAR(100) NULL,
    district VARCHAR(100) NULL,
    state VARCHAR(100) NULL,
    country VARCHAR(100) NOT NULL DEFAULT 'India',
    pin_code VARCHAR(20) NULL,
    emergency_contact_name VARCHAR(100) NULL,
    emergency_contact_relation VARCHAR(50) NULL,
    emergency_contact_phone VARCHAR(32) NULL,
    designation VARCHAR(100) NOT NULL,
    department_id BIGINT NOT NULL,
    branch_id BIGINT NULL,
    employment_type VARCHAR(32) NOT NULL DEFAULT 'FULL_TIME',
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    joining_date DATE NOT NULL,
    leaving_date DATE NULL,
    reporting_manager_id BIGINT NULL,
    profile_photo_key VARCHAR(255) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(100) NOT NULL DEFAULT 'SYSTEM',
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME(6) NULL,
    deleted_by VARCHAR(100) NULL,

    CONSTRAINT pk_employees PRIMARY KEY (id),
    CONSTRAINT uk_employees_public_id UNIQUE (public_id),
    CONSTRAINT uk_emp_hospital_number UNIQUE (hospital_id, employee_number),
    CONSTRAINT uk_emp_hospital_email UNIQUE (hospital_id, email),
    CONSTRAINT uk_emp_user_id UNIQUE (user_id),
    CONSTRAINT fk_emp_hospitals FOREIGN KEY (hospital_id) REFERENCES hospitals (id),
    CONSTRAINT fk_emp_users FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_emp_departments FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_emp_branches FOREIGN KEY (branch_id) REFERENCES hospital_branches (id) ON DELETE SET NULL,
    CONSTRAINT fk_emp_reporting_mgr FOREIGN KEY (reporting_manager_id) REFERENCES employees (id) ON DELETE SET NULL,

    INDEX idx_emp_hospital_status (hospital_id, status, is_deleted),
    INDEX idx_emp_hospital_dept (hospital_id, department_id, is_deleted),
    INDEX idx_emp_hospital_branch (hospital_id, branch_id, is_deleted),
    INDEX idx_emp_hospital_designation (hospital_id, designation),
    INDEX idx_emp_hospital_name (hospital_id, first_name, last_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE employee_lifecycle_events (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(36) NOT NULL,
    hospital_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    previous_status VARCHAR(24) NULL,
    new_status VARCHAR(24) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    effective_date DATE NOT NULL,
    actor_username VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),

    CONSTRAINT pk_employee_lifecycle_events PRIMARY KEY (id),
    CONSTRAINT uk_emp_events_public_id UNIQUE (public_id),
    CONSTRAINT fk_emp_events_hospitals FOREIGN KEY (hospital_id) REFERENCES hospitals (id),
    CONSTRAINT fk_emp_events_employees FOREIGN KEY (employee_id) REFERENCES employees (id) ON DELETE CASCADE,

    INDEX idx_emp_events_emp (hospital_id, employee_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
